/* ============================================================
   StudyNook · tools/build-icons.js — regenerate the icon set
   ------------------------------------------------------------
   Builds app/shared/icons.js and extension/icons.js (identical)
   from Lucide's icon-nodes.json, keeping only the icons listed
   below so the bundle stays small. Lucide is ISC-licensed.

   Usage:
     npm pack lucide-static@1.55.0 && tar -xzf lucide-static-1.55.0.tgz
     node tools/build-icons.js package/icon-nodes.json
   ============================================================ */
'use strict';
const fs = require('fs');
const path = require('path');

const NAMES = [
  // navigation & chrome
  'house', 'list-checks', 'notebook-pen', 'app-window', 'globe', 'chart-column', 'settings', 'circle-question-mark',
  'book-open', 'minus', 'x', 'chevron-right', 'chevron-left', 'chevron-down', 'search',
  // timer & session
  'timer', 'hourglass', 'play', 'pause', 'square', 'skip-forward', 'lock', 'lock-open', 'clock', 'target',
  // status & feedback
  'circle-check', 'circle-alert', 'circle-dot', 'circle-x', 'triangle-alert', 'info', 'check', 'plus',
  'flame', 'award', 'trophy', 'sun', 'moon', 'sun-moon', 'monitor', 'sparkles',
  // ambience
  'cloud-rain', 'waves-horizontal', 'coffee', 'volume-x', 'volume-2',
  // tasks, notes, lists
  'link', 'external-link', 'trash', 'pencil', 'file-text', 'calendar', 'copy',
  // blocking
  'ban', 'infinity', 'bell-ring', 'zap', 'bell', 'library', 'scan-search', 'refresh-cw', 'shield', 'shield-check',
  'shield-off', 'plug', 'unplug', 'search-check', 'eye', 'life-buoy', 'hand',
  'gamepad-2', 'message-circle', 'music', 'tv',
  // companion & achievements
  'cat', 'egg', 'baby', 'graduation-cap', 'crown', 'sprout', 'mountain', 'star', 'sunrise', 'moon-star', 'leaf',
  'heart', 'flower',
  // settings & help
  'sliders-horizontal', 'palette', 'database', 'rocket', 'wrench', 'rotate-ccw', 'download', 'upload',
  'folder-open', 'power', 'languages'
];

const src = process.argv[2];
if (!src) { console.error('usage: node tools/build-icons.js <path to lucide icon-nodes.json>'); process.exit(1); }
const all = JSON.parse(fs.readFileSync(src, 'utf8'));
const picked = {};
const missing = [];
for (const n of NAMES) { if (all[n]) picked[n] = all[n]; else missing.push(n); }
if (missing.length) { console.error('missing icons: ' + missing.join(', ')); process.exit(1); }

const out = `/* ============================================================
   StudyNook · icons.js — GENERATED by tools/build-icons.js
   Lucide icons (ISC licence, https://lucide.dev). Do not edit by
   hand: add the name to tools/build-icons.js and re-run it.
   app/shared/icons.js and extension/icons.js must stay identical.
   ============================================================ */
(function (root, factory) {
  if (typeof module !== 'undefined' && module.exports) module.exports = factory();
  else root.NookIcons = factory();
})(typeof self !== 'undefined' ? self : this, function () {
  'use strict';
  const NODES = ${JSON.stringify(picked)};
  const esc = (v) => String(v).replace(/[&<>"]/g, (c) => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;' }[c]));
  /** svg(name, { size, cls, label }) → markup string. Unknown names render an empty box. */
  function svg(name, opts) {
    opts = opts || {};
    const size = opts.size || 20;
    const kids = (NODES[name] || []).map(([tag, attrs]) =>
      '<' + tag + Object.keys(attrs).map((k) => ' ' + k + '="' + esc(attrs[k]) + '"').join('') + '/>').join('');
    const a11y = opts.label ? ' role="img" aria-label="' + esc(opts.label) + '"' : ' aria-hidden="true"';
    return '<svg xmlns="http://www.w3.org/2000/svg" width="' + size + '" height="' + size + '" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2" stroke-linecap="round" stroke-linejoin="round" class="icon' + (opts.cls ? ' ' + esc(opts.cls) : '') + '"' + a11y + '>' + kids + '</svg>';
  }
  function has(name) { return Object.prototype.hasOwnProperty.call(NODES, name); }
  return { svg, has, NAMES: Object.keys(NODES) };
});
`;
const root = path.join(__dirname, '..');
for (const f of ['app/shared/icons.js', 'extension/icons.js']) fs.writeFileSync(path.join(root, f), out);
console.log('wrote ' + Object.keys(picked).length + ' icons to app/shared/icons.js and extension/icons.js');
